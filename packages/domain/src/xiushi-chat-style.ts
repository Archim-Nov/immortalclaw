export function dialogueChannelForAction(actionId: string): DialogueChannel | null {
  if (
    actionId.startsWith("chat-up:")
    || actionId.startsWith("say:")
    || actionId.startsWith("reply-line:")
  ) {
    return "face";
  }
  if (actionId.startsWith("send-message:")) return "talisman";
  return null;
}

/** Full style for one channel. Face and talisman share the rules; the lead is the tone difference. */
export function buildDialogueStylePrompt(channel: DialogueChannel): string {
  const lead = channel === "face" ? FACE_DIALOGUE_LEAD : TALISMAN_DIALOGUE_LEAD;
  return `${lead}\n\n${DIALOGUE_STYLE_SHARED}`;
}

