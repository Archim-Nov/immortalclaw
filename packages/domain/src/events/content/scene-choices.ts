import type { EventEffect, SceneChoiceOption, SceneChoiceTemplate } from "../../model.js";
import type { EventTemplate } from "../../events.js";
import type { StateEventRow } from "./states/template.js";

type Semantic = EventTemplate["semanticType"];

interface Beat {
  readonly id: string;
  readonly name: string;
  readonly nameCn: string;
  readonly description: string;
  readonly semanticType: Semantic;
  readonly title: string;
  readonly prompt: string;
  readonly walk: readonly [string, string];
  readonly help: readonly [string, string];
  readonly take: readonly [string, string, number?];
  readonly risk?: readonly [string, string, number?];
}

interface StateBeat extends Beat {
  readonly stateId: string;
  readonly slot: string;
}

const CN_COUNT: Record<number, string> = {
  3: "三",
  4: "四",
  6: "六",
  8: "八",
  10: "十",
  11: "十一",
  12: "十二",
  14: "十四",
  16: "十六",
};

function countWord(value: number): string {
  return CN_COUNT[value] ?? String(value);
}

function outcomeSentence(effects: EventEffect): string {
  const stones = effects.spiritStones ?? 0;
  const reputation = effects.reputationChange ?? 0;
  const qi = effects.qi ?? 0;
  if (stones === 0 && reputation === 0 && qi === 0) {
    return "口袋和当地的名声都没有变。";
  }
  const parts: string[] = [];
  if (stones > 0) parts.push(`口袋里多了${countWord(stones)}枚灵石`);
  if (reputation > 0) parts.push("当地记下了一份薄人情");
  if (qi < 0) parts.push(`灵力沉了${countWord(Math.abs(qi))}点`);
  return `${parts.join("，")}。`;
}

function buildSceneChoice(beat: Beat): SceneChoiceTemplate {
  const takeStones = beat.take[2] ?? 8;
  const riskStones = beat.risk?.[2] ?? 12;
  if (takeStones < 6 || takeStones > 10) {
    throw new Error(`${beat.id} take reward is outside the thin band`);
  }
  if (beat.risk && (riskStones <= takeStones || riskStones > 16)) {
    throw new Error(`${beat.id} risk reward is outside the thin band`);
  }
  const options: SceneChoiceOption[] = [
    {
      id: "walk",
      label: beat.walk[0],
      summary: `${beat.walk[1]}${outcomeSentence({})}`,
      effectBundle: {},
    },
    {
      id: "help",
      label: beat.help[0],
      summary: `${beat.help[1]}${outcomeSentence({ spiritStones: 4, reputationChange: 1 })}`,
      effectBundle: { spiritStones: 4, reputationChange: 1 },
    },
    {
      id: "take",
      label: beat.take[0],
      summary: `${beat.take[1]}${outcomeSentence({ spiritStones: takeStones })}`,
      effectBundle: { spiritStones: takeStones },
    },
  ];
  if (beat.risk) {
    options.push({
      id: "risk",
      label: beat.risk[0],
      summary: `${beat.risk[1]}${outcomeSentence({ spiritStones: riskStones, qi: -4 })}`,
      effectBundle: { spiritStones: riskStones, qi: -4 },
    });
  }
  if (options.length < 3 || options.length > 4) {
    throw new Error(`${beat.id} must offer 3 or 4 options`);
  }
  return {
    title: beat.title,
    prompt: beat.prompt,
    expiresInTicks: 12,
    options: options as unknown as SceneChoiceTemplate["options"],
  };
}

function toGlobalRow(beat: Beat): EventTemplate {
  return {
    id: beat.id,
    layer: "global-common",
    source: beat.id.startsWith("tr-") ? "travel" : "exploration",
    semanticType: beat.semanticType,
    resultType: "resource",
    signalType: "decision",
    name: beat.name,
    nameCn: beat.nameCn,
    description: beat.description,
    baseWeight: 0.82,
    stateId: null,
    nodeType: null,
    minRealm: null,
    effects: {},
    sceneChoice: buildSceneChoice(beat),
  };
}

function toStateRow(beat: StateBeat): StateEventRow {
  return {
    slot: beat.slot,
    semanticType: beat.semanticType,
    resultType: "resource",
    title: beat.name,
    titleCn: beat.nameCn,
    description: beat.description,
    baseWeight: 0.78,
    effects: {},
    sceneChoice: buildSceneChoice(beat),
  };
}

